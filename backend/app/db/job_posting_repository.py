"""JSON postings alongside existing analyses; old JSON files are never rewritten."""

import hashlib
import json
import os
import re
import tempfile
import unicodedata
from datetime import datetime, timezone
from pathlib import Path
from threading import RLock
from urllib.parse import urlsplit, urlunsplit

from backend.app.db import job_repository
from backend.app.db import database
from backend.app.schemas.dashboard import JobPosting


storage_lock = RLock()


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def storage_root() -> Path:
    return job_repository.DEFAULT_JOB_STORAGE / "postings"


def atomic_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, prefix=".pending-", delete=False) as stream:
            temporary = Path(stream.name)
            json.dump(value, stream, ensure_ascii=False, indent=2)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def canonical_url(value: str) -> str:
    parsed = urlsplit(value)
    return urlunsplit((parsed.scheme.lower(), parsed.netloc.lower(), parsed.path, parsed.query, ""))


def posting_id(provider: str, board: str, external_id: str) -> str:
    key = json.dumps([provider, board, external_id], ensure_ascii=False)
    return "posting_" + hashlib.sha256(key.encode()).hexdigest()[:24]


def analysis_text(job: JobPosting) -> str:
    if job.legacy_analysis_id:
        # Legacy metadata was produced by an older model, not an authoritative
        # source. Do not turn its inferred title/company into new source evidence.
        return job.description
    # Explicit source metadata is part of the AI input and its cache identity.
    headers = [f"Job Title: {job.title}"]
    for label, value in [("Company", job.company), ("Location", job.location), ("Employment type", job.employment_type)]:
        if value:
            headers.append(f"{label}: {value}")
    return "\n".join(headers) + "\n\n" + job.description


def source_hash(job: JobPosting) -> str:
    text = unicodedata.normalize("NFC", analysis_text(job).replace("\r\n", "\n").replace("\r", "\n"))
    return hashlib.sha256(text.encode()).hexdigest()


def legacy_postings() -> list[JobPosting]:
    result = {}
    for path in sorted(job_repository.DEFAULT_JOB_STORAGE.glob("*.json"), key=lambda p: p.stat().st_mtime):
        try:
            record = json.loads(path.read_text(encoding="utf-8"))
            # Analyses generated by Dashboard already have a separately stored posting.
            if record.get("analysis_version"):
                continue
            analysis = job_repository.load_job_analysis(path.stem, job_repository.DEFAULT_JOB_STORAGE)
            if analysis is None:
                continue
            identity = canonical_url(analysis.source_url) if analysis.source_url else path.stem
            job = JobPosting(
                posting_id=posting_id("legacy", "", identity),
                title=analysis.job_requirements.job_title or "JD đã lưu",
                company=analysis.job_requirements.company, location=analysis.job_requirements.location,
                employment_type=analysis.job_requirements.employment_type, salary=analysis.job_requirements.salary,
                description=analysis.job_description_raw, source_name="JD đã lưu", external_id=identity,
                source_url=analysis.source_url, apply_url=analysis.source_url,
                imported_at=record.get("analyzed_at") or datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).isoformat(),
                legacy_analysis_id=analysis.job_id,
            )
            job.content_hash = source_hash(job)
            result[job.posting_id] = job
        except (ValueError, KeyError, OSError, TypeError):
            continue
    return list(result.values())


def list_postings() -> list[JobPosting]:
    jobs = {job.posting_id: job for job in legacy_postings()}
    for path in storage_root().glob("posting_*.json"):
        job = JobPosting.model_validate_json(path.read_text(encoding="utf-8"))
        jobs[job.posting_id] = job
    if database.enabled():
        for record in database.list_records("postings"):
            job = JobPosting.model_validate(record["data"])
            jobs[job.posting_id] = job
    return sorted(jobs.values(), key=lambda job: (job.fetched_at or job.imported_at, job.posting_id), reverse=True)


def get_posting(key: str) -> JobPosting | None:
    if not re.fullmatch(r"posting_[a-f0-9]{24}", key):
        raise ValueError("Posting ID không hợp lệ")
    if database.enabled():
        record = database.get_record("postings", key)
        if record:
            return JobPosting.model_validate(record)
    path = storage_root() / f"{key}.json"
    if path.exists():
        return JobPosting.model_validate_json(path.read_text(encoding="utf-8"))
    return next((job for job in legacy_postings() if job.posting_id == key), None)


def upsert_posting(job: JobPosting) -> tuple[JobPosting, str]:
    job = job.model_copy(deep=True)
    job.content_hash = source_hash(job)
    if database.enabled():
        with database.connect() as connection, connection.transaction():
            connection.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", (job.posting_id,))
            previous = get_posting(job.posting_id)
            status = "inserted" if previous is None else "unchanged" if previous.content_hash == job.content_hash else "updated"
            if previous:
                job.saved, job.imported_at = previous.saved, previous.imported_at
                if status == "updated":
                    database.put_record("posting_history", f"{job.posting_id}:{previous.content_hash}", previous.model_dump(mode="json"), immutable=True, connection=connection)
            database.put_record("postings", job.posting_id, job.model_dump(mode="json"), connection=connection)
        return job, status
    with storage_lock:
        previous = get_posting(job.posting_id)
        status = "inserted" if previous is None else "unchanged" if previous.content_hash == job.content_hash else "updated"
        if previous:
            job.saved = previous.saved
            job.imported_at = previous.imported_at
            if status == "updated":
                history = storage_root() / "history" / job.posting_id / f"{previous.content_hash}.json"
                if not history.exists():
                    atomic_json(history, previous.model_dump(mode="json"))
        atomic_json(storage_root() / f"{job.posting_id}.json", job.model_dump(mode="json"))
    return job, status


def set_saved(key: str, saved: bool) -> JobPosting:
    if database.enabled():
        with database.connect() as connection, connection.transaction():
            connection.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", (key,))
            job = get_posting(key)
            if job is None:
                raise LookupError("Không tìm thấy công việc")
            job.saved = saved
            database.put_record("postings", key, job.model_dump(mode="json"), connection=connection)
            return job
    with storage_lock:
        job = get_posting(key)
        if job is None:
            raise LookupError("Không tìm thấy công việc")
        job.saved = saved
        atomic_json(storage_root() / f"{key}.json", job.model_dump(mode="json"))
        return job


def read_aux(kind: str, key: str):
    if database.enabled():
        data = database.get_record(kind, key)
        if data is not None:
            return data
    path = storage_root() / "sync.json" if kind == "feed_state" else storage_root() / "analyses" / f"{key}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def write_aux(kind: str, key: str, data: dict):
    if database.enabled():
        database.put_record(kind, key, data)
    else:
        path = storage_root() / "sync.json" if kind == "feed_state" else storage_root() / "analyses" / f"{key}.json"
        atomic_json(path, data)
